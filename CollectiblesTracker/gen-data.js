// Regenerates Data.cs from the web checker's lists, so the mod and the page use the same items and positions.
// Usage: node gen-data.js <path to index.html>
const fs = require("fs");
const src = fs.readFileSync(process.argv[2], "utf8");

// Run the page's script against a tiny DOM stub, then read its CATEGORIES and LOCS.
const script = src.slice(src.lastIndexOf("<script>") + 8, src.lastIndexOf("</script>"));
const el = () => ({ checked: false, innerHTML: "", textContent: "", className: "", addEventListener() {}, insertAdjacentHTML() {}, classList: { add() {}, remove() {} }, click() {}, scrollIntoView() {} });
global.document = { getElementById: el, querySelector: el };
global.localStorage = { getItem: () => null, setItem() {} };
global.matchMedia = () => ({ matches: false });
global.navigator = {};
global.getSelection = () => ({});
const { CATEGORIES, LOCS } = eval(script + "\n({ CATEGORIES, LOCS })");

const NO_LOC = { 379: "You start with it (from the crash site)", 477: "Craft it yourself" };
const q = s => JSON.stringify(s);
let out = "// Generated by gen-data.js from the web checker's index.html. Don't edit by hand.\n" +
  "namespace CollectiblesTracker;\n\ninternal static partial class Data\n{\n    public static readonly Category[] Categories =\n    {\n";
for (const c of CATEGORIES) {
  const check = c.check[0].toUpperCase() + c.check.slice(1);
  out += `        new(${q(c.key)}, ${q(c.title)}, ${q(c.achievement)}, Check.${check}, new Item[]\n        {\n`;
  for (const [group, items] of c.groups) for (const [id, label, internal, hint] of items) {
    const locs = (LOCS[id] || []).map(l =>
      `new(${l[0]}f, ${l[1]}f, ${q(l[2] === "Overworld" ? "Above ground" : l[2])}, ${l[3] ? "true" : "false"})`);
    const where = hint || (c.key === "plated" && NO_LOC[id]) || c.where || "No fixed spot in the world";
    out += `            new(${id}, ${q(label)}, ${q(internal)}, ${q(group)}, ${q(where)}, new Loc[] { ${locs.join(", ")} }),\n`;
  }
  out += "        }),\n";
}
out += "    };\n}\n";
fs.writeFileSync("Data.cs", out);
console.log(CATEGORIES.map(c => c.key + ":" + c.groups.flatMap(g => g[1]).length).join(" "));
